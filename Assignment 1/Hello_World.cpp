#include <iostream>
using namespace std;

int main() {
    cout << "Hello World" << endl;

    // New line
    cout << "Hello\nWorld" << endl;

    // Tab
    cout << "Hello\tWorld" << endl;

    // Alarm sound
    cout << "Hello\a" << endl;

    // Carriage return
    cout << "Hello\rWorld" << endl;

    // Using endl
    cout << "Hello" << endl;
    cout << "World";

    return 0;
}